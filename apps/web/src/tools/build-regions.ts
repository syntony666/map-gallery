/// <reference types="node" />
// Rebuilds apps/web/src/data/taiwan-regions.ts from the delivered regions SVG.
//
// Usage: node apps/web/src/tools/build-regions.ts <source.svg>
//
// The delivered artwork lives on a 453.36pt canvas while the base image is
// 1600x1600px. The transform below maps artwork coordinates onto the inked
// area of maps/taiwan-land.png. Measured:
//   svg path bbox : x 151.55 - 302.42, y  85.14 - 369.37
//   png ink bbox  : x 464.00 - 1136.00, y 167.00 - 1434.00
// Recompute both bboxes when the artwork or the base image changes.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

type BBox = { minX: number; maxX: number; minY: number; maxY: number };
type Region = { id: string; paths: string[] };

const [sourcePath, outputPath = "src/data/taiwan-regions.ts"] =
  process.argv.slice(2);

if (!sourcePath) {
  console.error("usage: node apps/web/src/tools/build-regions.ts <source.svg> [out.ts]");
  process.exit(1);
}

const SVG_BBOX: BBox = { minX: 151.55, maxX: 302.42, minY: 85.14, maxY: 369.37 };
const PNG_BBOX: BBox = { minX: 464, maxX: 1136, minY: 167, maxY: 1434 };

const scaleX = (PNG_BBOX.maxX - PNG_BBOX.minX) / (SVG_BBOX.maxX - SVG_BBOX.minX);
const scaleY = (PNG_BBOX.maxY - PNG_BBOX.minY) / (SVG_BBOX.maxY - SVG_BBOX.minY);
const translateX = PNG_BBOX.minX - SVG_BBOX.minX * scaleX;
const translateY = PNG_BBOX.minY - SVG_BBOX.minY * scaleY;
const regionTransform = `translate(${translateX.toFixed(2)} ${translateY.toFixed(2)}) scale(${scaleX.toFixed(4)} ${scaleY.toFixed(4)})`;

const svg = readFileSync(sourcePath, "utf8");
const regions: Region[] = [];
const groupRe = /<g id="([^"]+)">([\s\S]*?)<\/g>/g;
let group: RegExpExecArray | null;
while ((group = groupRe.exec(svg)) !== null) {
  const paths = [...group[2].matchAll(/<path[^>]*\bd="([^"]+)"/g)].map(
    (m) => m[1],
  );
  if (paths.length === 0) continue;
  for (const d of paths) {
    if (!/z\s*$/i.test(d.trim())) {
      console.warn(`warning: ${group[1]} has an unclosed path (fill may leak)`);
    }
  }
  regions.push({ id: group[1], paths });
}

const file = `// Generated by apps/web/src/tools/build-regions.ts from ${basename(sourcePath)}.
// Do not edit by hand; regenerate after artwork changes.
export type MapRegion = { id: string; paths: string[] };

export const MAP_CANVAS_SIZE = 1600;
export const REGION_TRANSFORM = "${regionTransform}";

export const mapRegions: MapRegion[] = ${JSON.stringify(regions, null, 2)};
`;

writeFileSync(outputPath, file);
console.log(
  `wrote ${outputPath}: ${regions.length} regions, transform ${regionTransform}`,
);
